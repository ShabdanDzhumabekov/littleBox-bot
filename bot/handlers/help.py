"""
Обработчик команды /help: показывает список доступных команд и функций.
"""

from aiogram import Router, types
from aiogram.filters import Command

router = Router()

@router.message(Command("help"))
async def cmd_help(message: types.Message):
    """
    Обрабатывает команду /help и отправляет список возможностей бота.
    """
    await message.answer(
        "ℹ️ <b>Что умеет этот бот:</b>\n\n"
        "📦 <b>Объявления</b>\n"
        "• Разместить объявление на доставку (отправить, получить)\n"
        "• Найти посылку по точному маршруту\n"
        "• Управлять своими объявлениями:\n✏️ редактировать, ❌ удалить\n\n"
        "🛫 <b>Маршруты</b>\n"
        "• Разместить свой маршрут путешествия\n"
        "• Найти подходящего путешественника (по городу и/или стране)\n"
        "• Управлять своими маршрутами\n\n"
        "👤 <b>Навигация</b>\n"
        "/start — перезапуск бота и меню\n"
        "/help — показать это сообщение\n"
        "/cancel - Сбрасывает состояние пользователя\n"
        "и возвращает в главное меню\n"
        "/rules — правила безопасности\n\n"
        "📬 <b>Уведомление</b>\n"
        "бот будет вас уведомлять о новых объявлениях с таким же маршрутом\n\n"
        "📍 Используй кнопки внизу для удобства!"
    )